async (page) => {
  const base = "http://127.0.0.1:3000";
  const assert = (value,message) => { if (!value) throw new Error(message); };
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${base}/login`);
  await page.evaluate(() => { localStorage.removeItem("waypoint.demo.dispatch.v1"); localStorage.removeItem("waypoint.demo.session.v1"); sessionStorage.removeItem("waypoint.demo.session.v1"); });
  await page.reload();
  await page.getByRole("button",{name:/Dispatcher Planning office/}).click();
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await page.getByRole("heading",{name:"Today’s overview",exact:true}).waitFor();
  await page.setViewportSize({width:1440,height:900});
  await page.evaluate(() => document.fonts.ready);
  await page.locator(".overview-pie-frame svg").first().waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollHeight === innerHeight),"Desktop shell has page overflow instead of internal panel scrolling");
  assert(await page.locator(".overview-pie-frame svg").count() === 5,"Missing pie/donut charts");
  const statistics = await page.locator(".overview-stats > div strong").allTextContents();
  assert(JSON.stringify(statistics) === JSON.stringify(["6","2","0","1 / 4","1 / 2"]),`Incorrect fixture totals: ${statistics}`);
  const nav = page.getByRole("navigation",{name:"Dispatcher navigation"});
  await page.screenshot({path:".impeccable/review/overview-desktop.png",fullPage:true});
  await page.getByRole("button",{name:"Expand navigation",exact:true}).click();
  await page.waitForTimeout(300);
  assert(await page.getByRole("button",{name:"Collapse navigation",exact:true}).getAttribute("aria-expanded") === "true","Navigation did not expand");
  await page.screenshot({path:".impeccable/review/overview-expanded.png",fullPage:true});
  await page.getByRole("button",{name:"Collapse navigation",exact:true}).click();
  await page.getByRole("button",{name:"Close planning drawer",exact:true}).click();
  await page.waitForTimeout(300);
  await page.getByRole("button",{name:"Open planning drawer",exact:true}).waitFor();
  assert(await page.getByLabel("Planning drawer width",{exact:true}).count() === 0,"Closed drawer retained invisible controls");
  await page.screenshot({path:".impeccable/review/overview-drawer-closed.png",fullPage:true});
  await page.getByRole("button",{name:"Open planning drawer",exact:true}).click();
  const slider = page.getByRole("slider",{name:"Planning drawer width",exact:true});
  await slider.focus(); await page.keyboard.press("End");
  await page.waitForTimeout(300);
  assert(await slider.inputValue() === "390","Keyboard resize did not move slider");
  assert(Math.round(await page.locator(".overview-drawer").evaluate(el => el.getBoundingClientRect().width)) === 390,"Drawer width did not follow slider");
  await page.keyboard.press("Home"); await page.keyboard.press("ArrowRight"); await page.keyboard.press("ArrowRight"); await page.keyboard.press("ArrowRight");
  for (const selector of [".overview-scroll",".overview-drawer-scroll"]) {
    const scrolls = await page.locator(selector).evaluate(el => { el.scrollTop = 10000; return el.scrollTop > 0 && el.scrollHeight > el.clientHeight; });
    assert(scrolls,`${selector} is not independently scrollable`);
  }
  assert(await page.evaluate(() => window.scrollY) === 0,"Scrolling a panel moved the whole desktop page");
  await page.screenshot({path:".impeccable/review/overview-scrolled.png",fullPage:true});
  await page.locator(".overview-scroll").evaluate(el => {el.scrollTop = 0;});
  await page.locator(".overview-drawer-scroll").evaluate(el => {el.scrollTop = 0;});
  await page.getByRole("button",{name:"Next month",exact:true}).click();
  await page.getByRole("heading",{name:"November 2026",exact:true}).waitFor();
  await page.getByRole("button",{name:"Previous month",exact:true}).click();
  await page.getByRole("button",{name:"Select 2026-10-04",exact:true}).click();
  await page.getByRole("heading",{name:"No demo orders for this day",exact:true}).waitFor();
  await page.getByRole("button",{name:"Return to demo day",exact:true}).click();
  await page.getByRole("heading",{name:"Fleet distribution",exact:true}).waitFor();
  await page.getByLabel("Depot",{exact:true}).selectOption("Kandy");
  assert(JSON.stringify(await page.locator(".overview-stats > div strong").allTextContents()) === JSON.stringify(["2","0","0","0 / 2","0 / 1"]),"Kandy statistics wrong");
  await page.getByLabel("Depot",{exact:true}).selectOption("Peliyagoda");
  await nav.getByRole("button",{name:"Order intake",exact:true}).click();
  await page.getByRole("heading",{name:"Order intake",exact:true}).waitFor();
  await page.getByLabel("Filter by brand",{exact:true}).selectOption("Tech");
  await page.getByLabel("Search orders",{exact:true}).fill("unmatched previous filter");
  await nav.getByRole("button",{name:"Dashboard",exact:true}).click();
  await page.locator(".overview-drawer-scroll").evaluate(el => {el.scrollTop = 10000;});
  await page.locator(".companion-order").filter({hasText:"ORD-1044"}).click();
  await page.getByRole("heading",{name:"Order intake",exact:true}).waitFor();
  assert(await page.getByLabel("Search orders",{exact:true}).inputValue() === "ORD-1044","Queue order ID was not retained");
  assert(await page.getByLabel("Filter by brand",{exact:true}).inputValue() === "All brands","Conflicting brand filter was not cleared");
  assert(await page.getByLabel("Select ORD-1044",{exact:true}).isChecked(),"Queue order was not selected");
  assert(await page.getByLabel("Select ORD-1044",{exact:true}).evaluate(el => document.activeElement === el),"Queue order was not focused");
  await page.screenshot({path:".impeccable/review/overview-order-handoff.png",fullPage:true});
  await page.getByLabel("Select ORD-1044",{exact:true}).uncheck();
  await page.getByLabel("Search orders",{exact:true}).fill("");
  await page.getByLabel("Select ORD-1043",{exact:true}).check();
  await page.getByRole("button",{name:"Defer orders",exact:true}).click();
  await page.getByLabel("Decision note",{exact:true}).fill("No available refrigerated van; prioritize this order on the next run.");
  await page.getByRole("button",{name:"Save deferral",exact:true}).click();
  await nav.getByRole("button",{name:"Dashboard",exact:true}).click();
  assert((await page.locator(".overview-stats > div strong").allTextContents())[2] === "1","Deferral not reflected in dashboard");
  await page.evaluate(() => localStorage.removeItem("waypoint.demo.dispatch.v1"));
  await page.reload(); await page.getByRole("heading",{name:"Today’s overview",exact:true}).waitFor();
  for (const width of [1024,390,320]) {
    await page.setViewportSize({width,height:844});
    await page.waitForTimeout(300);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),`Overflow at ${width}`);
    await page.screenshot({path:`.impeccable/review/overview-${width}.png`,fullPage:true});
    await page.getByRole("button",{name:"Close planning drawer",exact:true}).click();
    await page.getByRole("button",{name:"Open planning drawer",exact:true}).click();
  }
  assert(errors.length === 0,errors.join(","));
  await page.setViewportSize({width:1440,height:900});
  return "Passed: five pie/donut charts and fixture counts, navigation/drawer toggles, keyboard width slider, independent panel scrolling, calendar/date empty state, depot filtering, order-card filter/selection/focus handoff, plan-to-chart updates, 1024/390/320px layouts; no page errors.";
}
